SetSeed(1);
SetVerbose("TwoDescent",1);
SetVerbose("ECSaturation",1);
curve := EllipticCurve([Rationals() | 0,-202,0,9801,0]);
generator := curve![49,336,1];
torsion, torsion_map := TorsionSubgroup(curve);
assert Invariants(torsion) eq [2,2];
selmer, selmer_map := TwoSelmerGroup(curve);
assert Invariants(selmer) eq [2,2,2];
assert Order(generator) eq 0;
saturated, proved := Saturation([generator] : TorsionFree := true);
assert proved and #saturated eq 1;
torsion_points := [point @ torsion_map : point in torsion];
assert exists{point : point in torsion_points | saturated[1] eq generator+point or saturated[1] eq -generator+point};
printf "TORSION_INVARIANTS %o\n", Invariants(torsion);
printf "TWO_SELMER_INVARIANTS %o\n", Invariants(selmer);
printf "SATURATION_PROVED %o SATURATED_BASIS %o\n", proved, saturated;
print "PASS_ALGEBRAIC_DESCENT_AND_FULL_SATURATION_WITHOUT_ANALYTIC_RANK_CALL";
quit;
